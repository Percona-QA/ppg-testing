"""
REPACK (PostgreSQL 19+) on pg_tde tables.

PostgreSQL 19 adds the REPACK command (VACUUM FULL / CLUSTER, plus a
CONCURRENTLY mode built on logical decoding). REPACK rewrites a table into
new files, so for ``tde_heap`` tables it must keep the data intact and keep
every rewritten file encrypted: the table, its indexes and its TOAST table.

* ``REPACK t`` and ``REPACK t USING INDEX i`` on a ``tde_heap`` table: data
  unchanged, table rewritten, table/indexes/TOAST encrypted, and the
  plaintext marker stored in every row never readable in the data files.
* ``REPACK (CONCURRENTLY)`` on a ``tde_heap`` table: upstream refuses it for
  non-``heap`` access methods. The test accepts a clean refusal (data
  untouched) or, if pg_tde supports it, the same checks as above; the
  outcome is printed. When supported, it is also run under concurrent
  writes (no lost or extra rows).
* ``REPACK (CONCURRENTLY)`` on a plain ``heap`` table with WAL encryption on,
  under concurrent writes: logical decoding of encrypted WAL, no lost rows.
* Repacked tables stay readable and identical after a restart, a principal
  key rotation and another restart.

Converted from the manual script repack_tde_manual_tests.sh (T1-T6).
Rows per table: ``REPACK_TDE_ROWS`` (default 50000; more rows = longer
REPACK and a wider window for the concurrent writers).
"""
from __future__ import annotations

import os
import subprocess
import time
from pathlib import Path
from typing import Dict, Generator, List

import pytest

from lib import PgCluster, TdeManager
from lib.cluster import initdb_args_no_data_checksums, libpq_superuser


pytestmark = [pytest.mark.encryption]

ROWS = int(os.environ.get("REPACK_TDE_ROWS", "50000"))
MARKER = "PLAINTEXT_MARKER_7f3a"  # stored in every row; must never be readable on disk
WRITE_SECONDS = 15  # concurrent writers run this long; REPACK starts WRITER_LEAD in
WRITER_LEAD = 3

# REPACK (CONCURRENTLY) uses logical decoding.
_REPACK_PARAMS: Dict[str, str] = {
    "shared_preload_libraries": "'pg_tde'",
    "wal_level": "logical",
    "max_wal_size": "'4GB'",
}


# ── fixtures ──────────────────────────────────────────────────────────────────


@pytest.fixture
def repack_cluster(pg_factory) -> Generator[PgCluster, None, None]:
    """A started PG 19+ cluster with pg_tde set up and wal_level = logical."""
    cluster = pg_factory("repack")
    cluster.initdb(extra_args=initdb_args_no_data_checksums(cluster.install_dir))
    if cluster.major_version < 19:
        pytest.skip(f"REPACK is new in PostgreSQL 19 (this is {cluster.major_version})")
    cluster.write_default_config("primary", extra_params=_REPACK_PARAMS)
    cluster.add_hba_entry("local all all trust")
    cluster.add_hba_entry("host  all all 127.0.0.1/32 trust")
    cluster.start()
    tde = TdeManager(cluster)
    tde.create_extension()
    # A key file per test, so parallel workers never share one.
    tde.add_global_key_provider_file(keyfile=str(cluster.data_dir.parent / "repack_keys.per"))
    tde.set_global_principal_key()  # server (WAL) key and database key
    yield cluster


# ── helpers ───────────────────────────────────────────────────────────────────


def _make_table(cluster: PgCluster, name: str, am: str) -> None:
    """ROWS rows (marker in every row, a TOASTed value on every 1000th), an
    index, then a third of the rows deleted so REPACK has something to reclaim.
    ``pad`` is stored EXTERNAL (uncompressed) so a TOASTed marker would be
    readable on disk if TOAST were not encrypted."""
    cluster.execute(
        f"""
        CREATE TABLE {name} (
            id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            val text NOT NULL,
            pad text
        ) USING {am};
        ALTER TABLE {name} ALTER COLUMN pad SET STORAGE EXTERNAL;
        CREATE INDEX {name}_val_idx ON {name} (val);
        INSERT INTO {name} (id, val, pad)
          SELECT g, '{MARKER}-' || g,
                 CASE WHEN g % 1000 = 0 THEN repeat('{MARKER}', 2000) ELSE md5(g::text) END
          FROM generate_series(1, {ROWS}) g;
        SELECT setval(pg_get_serial_sequence('{name}', 'id'), {ROWS});
        DELETE FROM {name} WHERE id % 3 = 0;
        """
    )


def _fingerprint(cluster: PgCluster, name: str) -> str:
    return cluster.fetchone(
        f"SELECT count(*) || ':' || md5(string_agg(id || ':' || val || ':' || "
        f"md5(coalesce(pad, '')), ',' ORDER BY id)) FROM {name}"
    )


def _filenode(cluster: PgCluster, name: str) -> str:
    return cluster.fetchone(f"SELECT pg_relation_filenode('{name}')")


def _relations(cluster: PgCluster, name: str) -> List[str]:
    """The table, its indexes and its TOAST table (and the TOAST index)."""
    return cluster.fetchall(
        f"""
        SELECT r::regclass::text FROM (
            SELECT '{name}'::regclass::oid AS r
            UNION ALL SELECT indexrelid FROM pg_index WHERE indrelid = '{name}'::regclass
            UNION ALL SELECT reltoastrelid FROM pg_class
                      WHERE oid = '{name}'::regclass AND reltoastrelid <> 0
            UNION ALL SELECT i.indexrelid FROM pg_class c JOIN pg_index i ON i.indrelid = c.reltoastrelid
                      WHERE c.oid = '{name}'::regclass
        ) x
        """
    )


def _assert_encrypted(cluster: PgCluster, name: str) -> None:
    rels = _relations(cluster, name)
    not_encrypted = [
        r for r in rels
        if cluster.fetchone(f"SELECT pg_tde_is_encrypted('{r}'::regclass)") != "t"
    ]
    assert not not_encrypted, f"{name}: not encrypted after REPACK: {not_encrypted} (of {rels})"


def _assert_no_plaintext(cluster: PgCluster, name: str) -> None:
    """The marker can't be found in the files of the table or its TOAST table."""
    cluster.execute("CHECKPOINT")
    paths = cluster.fetchall(
        f"""
        SELECT pg_relation_filepath(r) FROM (
            SELECT '{name}'::regclass AS r
            UNION ALL SELECT reltoastrelid::regclass FROM pg_class
                      WHERE oid = '{name}'::regclass AND reltoastrelid <> 0
        ) x
        """
    )
    marker = MARKER.encode()
    leaks = []
    for rel_path in paths:
        base = cluster.data_dir / rel_path
        # main fork and its 1 GB segments (base, base.1, ...)
        for f in sorted(base.parent.glob(base.name + "*")):
            if f.name != base.name and not f.name[len(base.name) + 1:].isdigit():
                continue  # _fsm / _vm forks hold no tuple data
            if marker in f.read_bytes():
                leaks.append(str(f))
    assert not leaks, f"{name}: plaintext marker found in {leaks}"


def _repack(cluster: PgCluster, sql: str) -> subprocess.CompletedProcess:
    return cluster.execute_allow_error(sql)


class _Writer:
    """Concurrent inserts into ``table`` (each also recorded in ``audit`` in
    the same transaction) plus updates of existing rows, via pgbench."""

    def __init__(self, cluster: PgCluster, table: str, audit: str, seconds: int) -> None:
        cluster.execute(f"CREATE TABLE {audit} (id bigint PRIMARY KEY)")
        script = cluster.data_dir.parent / f"writer_{table}.sql"
        script.write_text(
            f"\\set v random(1, {ROWS})\n"
            "BEGIN;\n"
            f"INSERT INTO {table} (val, pad) VALUES ('{MARKER}-w' || :v, md5(:v::text)) "
            "RETURNING id AS newid \\gset\n"
            f"INSERT INTO {audit} (id) VALUES (:newid);\n"
            f"UPDATE {table} SET pad = md5(pad) WHERE id = :v;\n"
            "END;\n"
        )
        self.log = cluster.data_dir.parent / f"pgbench_{table}.log"
        self.proc = subprocess.Popen(
            [
                str(cluster.bin / "pgbench"), "-n",
                "-h", str(cluster.socket_dir), "-p", str(cluster.port),
                "-U", libpq_superuser(),
                "-c", "4", "-T", str(seconds), "-f", str(script), "postgres",
            ],
            stdout=self.log.open("w"), stderr=subprocess.STDOUT,
        )

    def wait(self) -> None:
        rc = self.proc.wait(timeout=WRITE_SECONDS + 120)
        assert rc == 0, f"pgbench writer failed (rc={rc}):\n{self.log.read_text()[-2000:]}"


def _assert_no_lost_rows(cluster: PgCluster, table: str, audit: str) -> None:
    missing = cluster.fetchone(
        f"SELECT count(*) FROM {audit} a WHERE NOT EXISTS (SELECT 1 FROM {table} t WHERE t.id = a.id)"
    )
    extra = cluster.fetchone(
        f"SELECT count(*) FROM {table} t WHERE t.id > {ROWS} "
        f"AND NOT EXISTS (SELECT 1 FROM {audit} a WHERE a.id = t.id)"
    )
    written = int(cluster.fetchone(f"SELECT count(*) FROM {audit}"))
    assert written > 0, "the concurrent writers committed nothing"
    assert (missing, extra) == ("0", "0"), (
        f"{table}: {missing} of {written} concurrent inserts missing, {extra} unexpected rows"
    )


def _concurrently_refused(result: subprocess.CompletedProcess) -> bool:
    return result.returncode != 0 and 'only supported for the "heap" access method' in result.stderr


# ── tests ─────────────────────────────────────────────────────────────────────


@pytest.mark.parametrize(
    "using_index", [False, True], ids=["repack", "repack_using_index"]
)
def test_repack_tde_heap(repack_cluster: PgCluster, using_index: bool) -> None:
    """T1/T2: REPACK [USING INDEX] keeps a tde_heap table's data and encryption."""
    c = repack_cluster
    _make_table(c, "t1", "tde_heap")
    before, node = _fingerprint(c, "t1"), _filenode(c, "t1")

    sql = "REPACK t1 USING INDEX t1_val_idx" if using_index else "REPACK t1"
    result = _repack(c, sql)
    assert result.returncode == 0, f"{sql} failed: {result.stderr.strip()}"

    assert _fingerprint(c, "t1") == before, f"data changed by {sql}"
    assert _filenode(c, "t1") != node, f"{sql} did not rewrite the table"
    _assert_encrypted(c, "t1")
    _assert_no_plaintext(c, "t1")


def test_repack_concurrently_tde_heap(repack_cluster: PgCluster) -> None:
    """T3: REPACK (CONCURRENTLY) on tde_heap is either refused cleanly, as
    upstream does for non-heap tables, or works and keeps data and encryption."""
    c = repack_cluster
    _make_table(c, "t3", "tde_heap")
    before = _fingerprint(c, "t3")

    result = _repack(c, "REPACK (CONCURRENTLY) t3")
    if _concurrently_refused(result):
        print(f"\nREPACK (CONCURRENTLY) on tde_heap: REFUSED: {result.stderr.strip()}")
        assert _fingerprint(c, "t3") == before, "the refused REPACK changed the data"
        return
    assert result.returncode == 0, f"unexpected error: {result.stderr.strip()}"
    print("\nREPACK (CONCURRENTLY) on tde_heap: SUPPORTED")
    assert _fingerprint(c, "t3") == before, "data changed by REPACK (CONCURRENTLY)"
    _assert_encrypted(c, "t3")
    _assert_no_plaintext(c, "t3")


def test_repack_concurrently_tde_heap_under_writes(repack_cluster: PgCluster) -> None:
    """T4: if REPACK (CONCURRENTLY) works on tde_heap, no row is lost or added
    while other sessions write to the table."""
    c = repack_cluster
    _make_table(c, "t4", "tde_heap")
    probe = _repack(c, "REPACK (CONCURRENTLY) t4")
    if _concurrently_refused(probe):
        pytest.skip("REPACK (CONCURRENTLY) is refused on tde_heap (see the T3 test)")
    assert probe.returncode == 0, f"unexpected error: {probe.stderr.strip()}"

    writer = _Writer(c, "t4", "t4_audit", WRITE_SECONDS)
    try:
        time.sleep(WRITER_LEAD)
        result = _repack(c, "REPACK (CONCURRENTLY) t4")
    finally:
        writer.wait()
    assert result.returncode == 0, f"REPACK (CONCURRENTLY) under writes failed: {result.stderr.strip()}"
    _assert_no_lost_rows(c, "t4", "t4_audit")
    _assert_encrypted(c, "t4")
    _assert_no_plaintext(c, "t4")


def test_repack_concurrently_heap_with_wal_encryption(repack_cluster: PgCluster) -> None:
    """T5: REPACK (CONCURRENTLY) of a plain heap table decodes encrypted WAL
    correctly: no row lost or added under concurrent writes."""
    c = repack_cluster
    tde = TdeManager(c)
    tde.enable_wal_encryption()  # restarts the server
    assert tde.is_wal_encrypted(), "WAL encryption is not on"

    _make_table(c, "t5", "heap")
    writer = _Writer(c, "t5", "t5_audit", WRITE_SECONDS)
    try:
        time.sleep(WRITER_LEAD)
        result = _repack(c, "REPACK (CONCURRENTLY) t5")
    finally:
        writer.wait()
    assert result.returncode == 0, f"REPACK (CONCURRENTLY) with encrypted WAL failed: {result.stderr.strip()}"
    _assert_no_lost_rows(c, "t5", "t5_audit")


def test_repacked_tables_survive_restart_and_key_rotation(repack_cluster: PgCluster) -> None:
    """T6: repacked tde_heap tables stay readable and identical after a
    restart, a principal key rotation and another restart."""
    c = repack_cluster
    _make_table(c, "t6a", "tde_heap")
    _make_table(c, "t6b", "tde_heap")
    for sql in ("REPACK t6a", "REPACK t6b USING INDEX t6b_val_idx"):
        result = _repack(c, sql)
        assert result.returncode == 0, f"{sql} failed: {result.stderr.strip()}"
    fp = {t: _fingerprint(c, t) for t in ("t6a", "t6b")}

    c.restart()
    assert {t: _fingerprint(c, t) for t in fp} == fp, "repacked tables differ after a restart"

    TdeManager(c).rotate_principal_key("repack_key_rotated")
    c.restart()
    assert {t: _fingerprint(c, t) for t in fp} == fp, (
        "repacked tables unreadable or changed after key rotation and restart"
    )

    log = c.read_log(last_n=2000)
    bad = [l for l in log.splitlines()
           if any(w in l for w in ("PANIC", "TRAP")) or
           ("FATAL" in l and "terminating connection due to administrator command" not in l)]
    assert not bad, "server log has PANIC/FATAL/TRAP:\n" + "\n".join(bad[:5])
